#!/usr/bin/env node
/**
 * Prints the SQL that seeds `translations` on `fragrances` and `collections` from the in-code
 * source of truth (src/features/catalog/translations.ts), so the seed and the database can never
 * disagree. Usage: `node scripts/catalog-translations-sql.mjs > supabase/migrations/<ts>_x.sql`
 * (Node 24 strips the TypeScript types on import.)
 */
import {
  collectionTranslations,
  fragranceTranslations,
} from "../src/features/catalog/translations.ts";

const literal = (value) => `'${JSON.stringify(value).replaceAll("'", "''")}'::jsonb`;

const lines = [
  "-- Generated by scripts/catalog-translations-sql.mjs — edit src/features/catalog/translations.ts",
  "-- and regenerate instead of hand-editing this file.",
  "",
  "alter table public.fragrances",
  "  add column if not exists translations jsonb not null default '{}'::jsonb;",
  "alter table public.collections",
  "  add column if not exists translations jsonb not null default '{}'::jsonb;",
  "",
];
for (const [slug, translations] of Object.entries(fragranceTranslations)) {
  lines.push(
    `update public.fragrances set translations = translations || ${literal(translations)}`,
    `  where slug = '${slug}';`,
  );
}
for (const [slug, translations] of Object.entries(collectionTranslations)) {
  lines.push(
    `update public.collections set translations = translations || ${literal(translations)}`,
    `  where slug = '${slug}';`,
  );
}
process.stdout.write(lines.join("\n") + "\n");
